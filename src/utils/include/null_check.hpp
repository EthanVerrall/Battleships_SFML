// ----------------------------------------------------------------------------
#define NULL_CHECK(obj)                           \
    if ((obj) == nullptr) {                       \
                                                  \
        LOG(Log_lvl::WARN) <<  _data.name << ": " \
        << #obj << " == nullptr";                 \
                                                  \
        return {};                                \
    }

// ----------------------------------------------------------------------------
#define NULL_CHECK_VOID(obj)                      \
    if ((obj) == nullptr) {                       \
                                                  \
        LOG(Log_lvl::WARN) <<  _data.name << ": " \
        << #obj << " == nullptr";                 \
                                                  \
        return;                                   \
    }